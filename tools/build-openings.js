// Converts the lichess-org/chess-openings TSV files (CC0) into data/openings.js.
// Every line is replayed through the rules engine, so a bad move fails the build.
// Usage: node tools/build-openings.js   (expects data/src/a.tsv .. e.tsv)
const fs = require('fs');
const path = require('path');
const { Chess } = require('../js/chess-engine.js');
const root = path.resolve(__dirname, '..');
const seen = new Map();
const out = [];
for (const f of ['a', 'b', 'c', 'd', 'e']) {
  const rows = fs.readFileSync(path.join(root, 'data/src', f + '.tsv'), 'utf8').trim().split('\n').slice(1);
  for (const row of rows) {
    const [eco, name, pgn] = row.split('\t');
    const tokens = pgn.replace(/\d+\.(\.\.)?/g, ' ').trim().split(/\s+/);
    const g = new Chess();
    const sans = tokens.map(t => {
      const m = g.move(t);
      if (!m) throw new Error(`Illegal move ${t} in ${name}: ${pgn}`);
      return m.san;
    });
    const key = sans.join(' ');
    if (seen.has(key)) continue; // same moves listed twice: keep the first name
    seen.set(key, true);
    out.push([eco, name, key]);
  }
}
const header = '/* Chess openings from lichess-org/chess-openings (CC0 public domain).\n' +
  ' * https://github.com/lichess-org/chess-openings\n' +
  ' * Each entry: [ECO code, name, moves in SAN separated by spaces]. Generated by tools/build-openings.js. */\n';
fs.writeFileSync(path.join(root, 'data/openings.js'),
  header + 'window.OPENINGS = [\n' + out.map(e => JSON.stringify(e)).join(',\n') + '\n];\n');
console.log(out.length + ' openings written to data/openings.js');
